const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('src/pages/admin/InvoicesPage.jsx', 'utf8');
const parse = source.match(/const parseLocaleFloat = \(val\) => \{[\s\S]*?\n\};/)[0];
const handler = source.match(/const handleOpenEdit = \(inv\) => \{[\s\S]*?\n  \};/)[0];
let form;
const context = { setEditModal() {}, setEditForm(value) { form = value; } };
vm.runInNewContext(`${parse}\n${handler}\nhandleOpenEdit({ client: { name: 'Prueba' }, items: [{ quantity: 1, price: 891, total: 1078.11 }, { quantity: 1, price: 7, total: 8.47 }], taxRate: 21 });`, context);
assert.deepEqual(Array.from(form.items, item => item.total), [891, 7]);
const subtotal = form.items.reduce((sum, item) => sum + item.total, 0);
const tax = Number((subtotal * form.taxRate / 100).toFixed(2));
assert.equal(subtotal, 898);
assert.equal(tax, 188.58);
assert.equal(Number((subtotal + tax).toFixed(2)), 1086.58);
vm.runInNewContext(`handleOpenEdit({ client: { name: 'Prueba' }, items: [{ quantity: '2', price: '3,25', total: 7.87 }], taxRate: 0 });`, context);
assert.equal(form.items[0].total, 6.5);
assert.equal(form.taxRate, 0);
console.log('Cálculo de borrador: ejemplos con IVA incluido previamente, decimales y tipo cero correctos.');
